// Uma área do acervo: a CDU da estante, os assuntos gravados nos livros e as
// buscas na Open Library que trazem edições em português dessa área.
export interface CatalogArea {
  key: string
  label: string
  cdu: string
  subjects: string[]
  // Buscas da Open Library (sintaxe de search.json, sem o filtro de idioma).
  queries: string[]
  // Começos de palavra (minúsculas, sem acento) que o título ou os assuntos do
  // livro precisam ter para ele entrar na área: a busca por assunto da Open
  // Library traz resultados soltos (ex.: romance em Administração).
  keywords: string[]
  // Quantos títulos a área deve ter no acervo gerado.
  target: number
}

